/**
 * @fileoverview OpenAPI document → the source files of a typed client
 * built on `@tundralibs/restler`: one method per operation, arguments
 * validated with `@tundralibs/guardian` before the request is sent, the
 * reply validated against the route's declared `response`, an `auth`
 * option built from the security schemes the routes require, and one
 * error class carrying the server's error envelope.
 * @module
 */
import {
  isUnknownSource,
  type SchemaSource,
  schemaSource,
} from './schemaSource.ts';

/** What {@link generateSdk} produces. */
export type GeneratedSdk = {
  /** File name → source text. */
  files: Record<string, string>;
  /** The generated method names, in document order. */
  methods: string[];
  /** Operations left out (`METHOD /path: reason`). */
  skipped: string[];
  /** Security schemes a route requires that the `auth` option cannot carry. */
  notes: string[];
};

type Json = Record<string, unknown>;

const METHODS = ['get', 'post', 'put', 'patch', 'delete'];

const isJson = (value: unknown): value is Json =>
  typeof value === 'object' && value !== null && !Array.isArray(value);

const literal = (value: unknown): string =>
  `'${String(value).replace(/[\\']/g, '\\$&')}'`;

const key = (name: string): string =>
  /^[A-Za-z_$][\w$]*$/.test(name) ? name : literal(name);

const words = (text: string): string[] =>
  text.split(/[^A-Za-z0-9]+/).filter((w) => w !== '');

const upperFirst = (text: string): string =>
  text.charAt(0).toUpperCase() + text.slice(1);

const pascal = (text: string): string => words(text).map(upperFirst).join('');

const camel = (text: string): string => {
  const name = pascal(text);
  return name.charAt(0).toLowerCase() + name.slice(1);
};

const jsonSchemaOf = (holder: unknown): unknown => {
  const content = isJson(holder) ? holder.content : undefined;
  const json = isJson(content) ? content['application/json'] : undefined;
  return isJson(json) ? json.schema : undefined;
};

/** A schema declaration pair, or nothing when the schema says nothing. */
const declare = (
  name: string,
  what: string,
  source: SchemaSource,
): string =>
  isUnknownSource(source) ? '' : `/** ${what} */
export type ${name} = ${source.type};
/** Validates {@link ${name}}. */
export const ${name}Schema: BaseGuardian<${name}> = ${source.guard};

`;

/** The client's `auth` option, as source, for the schemes its routes require. */
type AuthSource = {
  /** Members of the `<Name>Auth` union; empty = RESTler's own `auth`. */
  members: string[];
  /** Statements placing each API key on the outgoing request. */
  inject: string[];
  notes: string[];
};

function authSource(required: string[], declared: Json): AuthSource {
  const kinds = new Set<string>();
  const fields: string[] = [];
  const inject: string[] = [];
  const notes: string[] = [];
  for (const name of required) {
    const scheme = declared[name];
    if (!isJson(scheme)) {
      notes.push(
        `security scheme "${name}" is not declared to openapi() or docs(): the client cannot send it`,
      );
    } else if (scheme.type === 'apiKey') {
      if (name === 'type') {
        throw new Error(
          'an apiKey security scheme named "type" collides with the auth option\'s own field — rename the scheme',
        );
      }
      const value = `auth[${literal(name)}]`;
      const target = scheme.in === 'query'
        ? `(endpoint.query ??= {})[${literal(scheme.name)}] = ${value}`
        : scheme.in === 'header'
        ? `headers[${literal(scheme.name)}] = ${value}`
        : `headers.Cookie = [
        headers.Cookie,
        ${literal(`${scheme.name}=`)} + encodeURIComponent(${value}),
      ].filter(Boolean).join('; ')`;
      fields.push(`${key(name)}?: string`);
      inject.push(`if (typeof ${value} === 'string') {
      ${target};
    }`);
    } else if (scheme.type === 'http' && scheme.scheme === 'basic') {
      kinds.add('BASIC');
    } else if (scheme.type === 'http' && scheme.scheme !== 'bearer') {
      notes.push(
        `security scheme "${name}" uses HTTP ${scheme.scheme}: the client cannot send it`,
      );
    } else {
      // http bearer, oauth2 and openIdConnect all end in a bearer token.
      kinds.add('BEARER');
    }
  }
  return {
    members: [
      ...(kinds.has('BEARER')
        ? [`{ type: 'BEARER'; token: string; prefix?: string }`]
        : []),
      ...(kinds.has('BASIC')
        ? [`{ type: 'BASIC'; username: string; password: string }`]
        : []),
      ...(fields.length > 0
        ? [`{ type: 'CUSTOM'; ${fields.join('; ')} }`]
        : []),
    ],
    inject,
    notes,
  };
}

function errorsFile(name: string, constant: string, codes: string[]): string {
  return `/**
 * @fileoverview The error model of the ${name} client. Generated by
 * \`rapid sdk\` — regenerate rather than edit.
 * @module
 */
import { RESTlerError } from '@tundralibs/restler';

/**
 * Error code → message template. \`RAPID_*\` codes are the server's own and
 * carry its message; the rest are raised by this client.
 */
export const ${constant}_ERROR_CODES = {
  UNKNOWN_ERROR:
    'The API answered with an error this client does not know (HTTP \${status}).',
  REQUEST_INVALID: 'The \${what} is invalid; the request was not sent.',
  RESPONSE_INVALID:
    'The reply to \${operation} did not match its declared schema.',
  RATE_LIMITED: 'Still rate limited after the retry (HTTP 429).',
  TIMEOUT: 'No answer within the \${timeoutSeconds}s timeout.',
  NETWORK_ERROR:
    'The request failed before a response (DNS, TLS or connection failure).',
${codes.map((code) => `  ${code}: '\${serverMessage}',`).join('\n')}
} as const;

/** A valid ${name} error code. */
export type ${name}ErrorCode = keyof typeof ${constant}_ERROR_CODES;

/** Metadata carried by a {@link ${name}Error}. */
export type ${name}ErrorMetadata = {
  vendor: string;
  /** The server's code, when this client does not know it. */
  originalCode?: string;
} & Record<string, unknown>;

const TRANSIENT_CODES = new Set<string>([
  'RATE_LIMITED',
  'TIMEOUT',
  'NETWORK_ERROR',
]);
const TRANSIENT_STATUSES = new Set<unknown>([429, 502, 503, 504]);

/**
 * Every failure the ${name} client throws. Branch on \`code\`; the HTTP
 * \`status\`, the server's \`details\` and its \`requestId\` are read with
 * \`getContextValue()\`.
 */
export class ${name}Error<
  M extends ${name}ErrorMetadata = ${name}ErrorMetadata,
> extends RESTlerError<M> {
  /** A key of {@link ${constant}_ERROR_CODES}. */
  public readonly code: ${name}ErrorCode;
  /** \`true\` when retrying later can help: no answer, a 429 or a 502-504. */
  public readonly transient: boolean;

  protected override get _messageTemplate(): string {
    return '[${name}] \${timeStamp}: \${message}';
  }

  constructor(code: ${name}ErrorCode, meta?: Omit<M, 'vendor'>, cause?: Error) {
    const context = { ...meta, vendor: '${name}' } as M;
    if (!(code in ${constant}_ERROR_CODES)) {
      context.originalCode = code;
      code = 'UNKNOWN_ERROR';
    }
    // A placeholder the throw site did not fill would render literally.
    for (const match of ${constant}_ERROR_CODES[code].matchAll(/\\$\\{(\\w+)\\}/g)) {
      const key = String(match[1]);
      if ((context as Record<string, unknown>)[key] === undefined) {
        (context as Record<string, unknown>)[key] = \`<\${key} unavailable>\`;
      }
    }
    super(${constant}_ERROR_CODES[code], context, cause);
    this.code = code;
    this.transient = TRANSIENT_CODES.has(code) ||
      TRANSIENT_STATUSES.has(context.status);
  }
}
`;
}

function clientFile(
  name: string,
  title: string,
  schemaImports: string[],
  methods: string[],
  auth: AuthSource,
): string {
  return `/**
 * @fileoverview The ${title} client. Generated by \`rapid sdk\` —
 * regenerate rather than edit.
 * @module
 */
import {
  type BaseGuardian,
  Guardian,
  GuardianError,
} from '@tundralibs/guardian';
import {
  type ResponseBody,
  RESTler,
  type RESTlerEndpoint,
  type RESTlerEvents,
  type RESTlerOptions,
  RESTlerRateLimitError,
  RESTlerRequestError,
  type RESTlerRequestOptions,
  type RESTlerResponse,
  RESTlerResponseValidationError,
  RESTlerTimeoutError,
} from '@tundralibs/restler';
import type { EventOptionKeys } from '@tundralibs/utils';
import { ${name}Error, type ${name}ErrorCode } from './errors.ts';
${
    schemaImports.length === 0
      ? ''
      : `import {\n${
        schemaImports.map((i) => `  ${i},`).join('\n')
      }\n} from './schemas.ts';\n`
  }
${
    auth.members.length === 0
      ? `/** Options of a {@link ${name}} client: \`baseURL\`, \`auth\`, \`timeout\`, … */
export type ${name}Options = RESTlerOptions;`
      : `/** The credential a {@link ${name}} client sends: one of the API's declared security schemes. */
export type ${name}Auth =
${auth.members.map((member) => `  | ${member}`).join('\n')};

/** Options of a {@link ${name}} client: \`baseURL\`, \`auth\`, \`timeout\`, … */
export type ${name}Options = Omit<RESTlerOptions, 'auth'> & {
  auth?: ${name}Auth;
};`
  }

/**
 * Typed client for ${title}. Every method validates its arguments
 * before the request is sent and the reply after it arrives.
 */
export class ${name} extends RESTler<${name}Options> {
  public readonly vendor: string = '${name}';

  constructor(options: EventOptionKeys<${name}Options, RESTlerEvents>) {
    super(options, { contentType: 'JSON' });
    this._responseHandler = (response) => this.__toError(response);
  }

${methods.join('\n')}${
    auth.inject.length === 0 ? '' : `
  /** Each API key of a \`CUSTOM\` auth goes where its security scheme declares it. */
  protected override _authInjector(
    endpoint: RESTlerEndpoint,
  ): void | Promise<void> {
    const auth = (endpoint.auth ?? this._getOption('auth')) as
      | Record<string, unknown>
      | undefined;
    if (auth?.type !== 'CUSTOM') return super._authInjector(endpoint);
    const headers = endpoint.headers ??= {};
    ${auth.inject.join('\n    ')}
  }
`
  }
  /** A timeout, a network failure and an exhausted rate-limit retry, as {@link ${name}Error}. */
  protected override async _makeRequest<H = ResponseBody, B = H>(
    endpoint: RESTlerEndpoint,
    options: RESTlerRequestOptions<H, B> = {},
  ): Promise<RESTlerResponse<B>> {
    try {
      return await super._makeRequest<H, B>(endpoint, options);
    } catch (error) {
      if (error instanceof RESTlerRateLimitError) {
        throw new ${name}Error('RATE_LIMITED', {
          status: 429,
          retryAfterSeconds: error.getContextValue('retryAfter'),
        }, error);
      }
      if (error instanceof RESTlerTimeoutError) {
        throw new ${name}Error('TIMEOUT', {
          timeoutSeconds: endpoint.timeout ?? this._getOption('timeout'),
        }, error);
      }
      // The two above and a validation failure extend RESTlerRequestError:
      // only a bare one is a failure before any response.
      if (
        error instanceof RESTlerRequestError &&
        !(error instanceof RESTlerResponseValidationError)
      ) {
        throw new ${name}Error('NETWORK_ERROR', {}, error);
      }
      throw error;
    }
  }

  /** Validate one argument; a failure never reaches the network. */
  private __check<T>(what: string, value: unknown, guard: BaseGuardian<T>): T {
    try {
      return guard.parse(value);
    } catch (error) {
      if (!(error instanceof GuardianError)) throw error;
      throw new ${name}Error('REQUEST_INVALID', {
        what,
        requestError: error.toJSON(),
      }, error);
    }
  }

  /** A validated path parameter, encoded as one path segment. */
  private __segment<T>(what: string, value: T, guard: BaseGuardian<T>): string {
    return encodeURIComponent(String(this.__check(what, value, guard)));
  }

  /** A validated body, as RESTler's JSON payload. */
  private __body<T>(
    what: string,
    value: T,
    guard?: BaseGuardian<T>,
  ): Record<string, unknown> {
    return (guard === undefined
      ? value
      : this.__check(what, value, guard)) as Record<string, unknown>;
  }

  /** Validated query arguments as strings; an unset one is left out. */
  private __query<T>(
    what: string,
    value: T | undefined,
    guard: BaseGuardian<T>,
  ): Record<string, string> {
    const query: Record<string, string> = {};
    if (value === undefined) return query;
    const checked = this.__check(what, value, guard) as Record<string, unknown>;
    for (const [key, item] of Object.entries(checked)) {
      if (item !== undefined && item !== null) query[key] = String(item);
    }
    return query;
  }

  /** Send, then validate the reply when the route declares its shape. */
  private async __call<B>(
    operation: string,
    endpoint: RESTlerEndpoint,
    guard?: BaseGuardian<B>,
  ): Promise<B> {
    try {
      const response = await this._makeRequest<unknown, B>(
        endpoint,
        guard === undefined
          ? {}
          : { responseSchema: (data) => guard.parse(data) },
      );
      return response.body as B;
    } catch (error) {
      if (!(error instanceof RESTlerResponseValidationError)) throw error;
      throw new ${name}Error('RESPONSE_INVALID', {
        operation,
        responseError: (error.cause as GuardianError | undefined)?.toJSON(),
      }, error);
    }
  }

  /** An error reply's envelope as a {@link ${name}Error}; anything else passes. */
  private __toError(response: RESTlerResponse<unknown>): unknown {
    const status = response.status ?? 0;
    if (status < 400) return response.body;
    const envelope = (typeof response.body === 'object' &&
        response.body !== null
      ? response.body
      : {}) as Record<string, unknown>;
    throw new ${name}Error(
      (typeof envelope.code === 'string'
        ? envelope.code
        : 'UNKNOWN_ERROR') as ${name}ErrorCode,
      {
        status,
        serverMessage: envelope.message,
        details: envelope.details,
        requestId: envelope.requestId,
        ...(status === 429
          ? { retryAfterSeconds: this._parseRetryAfter(response.headers) }
          : {}),
      },
    );
  }
}
`;
}

/**
 * Generate the client's source files from an OpenAPI document as
 * `buildOpenApi` assembles it. Operations that only answer HTML are
 * skipped; header parameters are not turned into arguments. When routes
 * require security schemes, the client's `auth` option is narrowed to
 * them: `BEARER` for an http bearer, oauth2 or openIdConnect scheme,
 * `BASIC` for http basic, and one `CUSTOM` field per apiKey scheme.
 *
 * @param doc - The OpenAPI document.
 * @param options - `name`: the client class name (default: the document
 *   title in PascalCase, or `Api`).
 * @throws {Error} when `name` is not a valid identifier, or two
 *   operations resolve to the same method name.
 */
export function generateSdk(
  doc: Record<string, unknown>,
  options: { name?: string } = {},
): GeneratedSdk {
  const info = isJson(doc.info) ? doc.info : {};
  const title = typeof info.title === 'string' ? info.title : 'API';
  const name = options.name ?? (pascal(title) || 'Api');
  if (!/^[A-Z][A-Za-z0-9]*$/.test(name)) {
    throw new Error(
      `"${name}" is not a usable class name — pass --name <PascalCase>`,
    );
  }
  const constant = name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase();

  const schemas: string[] = [];
  const schemaImports: string[] = [];
  const methods: string[] = [];
  const names: string[] = [];
  const skipped: string[] = [];
  const required: string[] = [];

  const paths = isJson(doc.paths) ? doc.paths : {};
  for (const [path, item] of Object.entries(paths)) {
    if (!isJson(item)) continue;
    for (const verb of METHODS) {
      const operation = item[verb];
      if (!isJson(operation)) continue;
      const label = `${verb.toUpperCase()} ${path}`;
      const ok = isJson(operation.responses)
        ? operation.responses['200']
        : undefined;
      const content = isJson(ok) && isJson(ok.content) ? ok.content : {};
      if (!('application/json' in content)) {
        skipped.push(`${label}: answers HTML only`);
        continue;
      }
      const method = typeof operation.operationId === 'string'
        ? camel(operation.operationId)
        : camel(`${verb} ${path}`);
      if (names.includes(method)) {
        throw new Error(
          `${label} resolves to the method name "${method}", which is taken — give the route an operationId`,
        );
      }
      names.push(method);
      const type = upperFirst(method);
      const use = (suffix: string, what: string, source: SchemaSource) => {
        if (isUnknownSource(source)) return undefined;
        schemas.push(declare(`${type}${suffix}`, what, source));
        schemaImports.push(`type ${type}${suffix}`, `${type}${suffix}Schema`);
        return `${type}${suffix}`;
      };

      const parameters =
        (Array.isArray(operation.parameters) ? operation.parameters : [])
          .filter(isJson);
      const args: string[] = [];
      const docs: string[] = [];

      // Path parameters, in path order, each validated inline.
      const urlPath = path.replace(/\{(\w+)\}/g, (_, param: string) => {
        const declared = parameters.find((p) =>
          p.in === 'path' && p.name === param
        );
        const source = schemaSource(declared?.schema);
        args.push(`${param}: ${source.type}`);
        docs.push(`@param ${param} - Path parameter.`);
        return `\${this.__segment('${param} of ${method}', ${param}, ${source.guard})}`;
      });

      const endpoint = [
        `method: '${verb.toUpperCase()}'`,
        `path: ${urlPath === path ? `'${path}'` : `\`${urlPath}\``}`,
      ];

      if (operation.requestBody !== undefined) {
        const body = use(
          'Body',
          `Request body of \`${method}\`.`,
          schemaSource(jsonSchemaOf(operation.requestBody)),
        );
        args.push(`body: ${body ?? 'unknown'}`);
        docs.push('@param body - Request body.');
        endpoint.push(
          `payload: this.__body('body of ${method}', body${
            body === undefined ? '' : `, ${body}Schema`
          })`,
        );
      }

      const queryParams = parameters.filter((p) => p.in === 'query');
      if (queryParams.length > 0) {
        const required = queryParams.filter((p) => p.required === true);
        const query = use(
          'Query',
          `Query arguments of \`${method}\`.`,
          schemaSource({
            type: 'object',
            properties: Object.fromEntries(
              queryParams.map((p) => [String(p.name), p.schema]),
            ),
            required: required.map((p) => String(p.name)),
          }),
        ) as string;
        args.push(`query${required.length === 0 ? '?' : ''}: ${query}`);
        docs.push('@param query - Query arguments.');
        endpoint.push(
          `query: this.__query('query of ${method}', query, ${query}Schema)`,
        );
      }

      const response = use(
        'Response',
        `Reply of \`${method}\`.`,
        schemaSource(
          content['application/json'] === undefined
            ? undefined
            : (content['application/json'] as Json).schema,
        ),
      );

      const security =
        (Array.isArray(operation.security) ? operation.security : [])
          .filter(isJson).flatMap((entry) => Object.keys(entry));
      for (const scheme of security) {
        if (!required.includes(scheme)) required.push(scheme);
      }

      const summary = [operation.summary, operation.description]
        .filter((line): line is string => typeof line === 'string');
      if (security.length > 0) {
        summary.push(`Auth: ${security.map((s) => `\`${s}\``).join(' or ')}.`);
      }
      methods.push(`  /**
${
        [...summary, `\`${label}\``, '', ...docs].map((line) =>
          `   * ${line}`.trimEnd()
        ).join('\n')
      }
   * @throws {${name}Error} \`REQUEST_INVALID\` before sending, the server's
   *   code on an error reply, \`RESPONSE_INVALID\`, or a transport code.
   */
  public async ${method}(${args.join(', ')}): Promise<${
        response ?? 'unknown'
      }> {
    return await this.__call('${method}', {
      ${endpoint.join(',\n      ')},
    }${response === undefined ? '' : `, ${response}Schema`});
  }
`);
    }
  }

  const components = isJson(doc.components) ? doc.components : {};
  const envelope = isJson(components.schemas)
    ? components.schemas.RapidError
    : undefined;
  const code = isJson(envelope) && isJson(envelope.properties)
    ? envelope.properties.code
    : undefined;
  const codes = isJson(code) && Array.isArray(code.enum)
    ? code.enum.filter((c): c is string => typeof c === 'string')
    : [];

  const auth = authSource(
    required,
    isJson(components.securitySchemes) ? components.securitySchemes : {},
  );

  return {
    files: {
      'mod.ts': `/**
 * @fileoverview The ${title} client. Generated by \`rapid sdk\` —
 * regenerate rather than edit.
 * @module
 */
export {
  ${name},${auth.members.length === 0 ? '' : `\n  type ${name}Auth,`}
  type ${name}Options,
} from './${name}.ts';
export * from './errors.ts';
export * from './schemas.ts';
`,
      [`${name}.ts`]: clientFile(name, title, schemaImports, methods, auth),
      'errors.ts': errorsFile(name, constant, codes),
      'schemas.ts': `/**
 * @fileoverview Request and reply schemas of ${title}. Generated
 * by \`rapid sdk\` — regenerate rather than edit.
 * @module
 */
import { type BaseGuardian, Guardian } from '@tundralibs/guardian';

${schemas.join('')}`,
    },
    methods: names,
    skipped,
    notes: auth.notes,
  };
}
