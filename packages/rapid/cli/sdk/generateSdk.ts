/**
 * @fileoverview OpenAPI document → the source files of a typed client
 * built on `@tundralibs/restler`: one method per operation, arguments
 * validated with `@tundralibs/guardian` before the request is sent, the
 * reply validated against the route's declared `response`, an `auth`
 * option built from the security schemes the routes require, and one
 * error class carrying the server's error envelope.
 * @module
 */
import { schemaRegistry } from './schemaRegistry.ts';
import { schemaSource } from './schemaSource.ts';

/** What {@link generateSdk} produces. */
export type GeneratedSdk = {
  /** File name → source text. */
  files: Record<string, string>;
  /** The generated method names, in document order. */
  methods: string[];
  /** Operations left out (`METHOD /path: reason`). */
  skipped: string[];
  /** Declared security schemes and servers the client leaves out, and why. */
  notes: string[];
};

type Json = Record<string, unknown>;

const METHODS = ['get', 'post', 'put', 'patch', 'delete'];

const isJson = (value: unknown): value is Json =>
  typeof value === 'object' && value !== null && !Array.isArray(value);

const literal = (value: unknown): string =>
  `'${String(value).replace(/[\\']/g, '\\$&')}'`;

const key = (name: string): string =>
  /^[A-Za-z_$][\w$]*$/.test(name) ? name : literal(name);

const words = (text: string): string[] =>
  text.split(/[^A-Za-z0-9]+/).filter((w) => w !== '');

const upperFirst = (text: string): string =>
  text.charAt(0).toUpperCase() + text.slice(1);

const pascal = (text: string): string => words(text).map(upperFirst).join('');

const camel = (text: string): string => {
  const name = pascal(text);
  return name.charAt(0).toLowerCase() + name.slice(1);
};

const jsonSchemaOf = (holder: unknown): unknown => {
  const content = isJson(holder) ? holder.content : undefined;
  const json = isJson(content) ? content['application/json'] : undefined;
  return isJson(json) ? json.schema : undefined;
};

/** The client's `auth` option, as source, for the schemes its routes require. */
type AuthSource = {
  /** Members of the `<Name>Auth` union; empty = RESTler's own `auth`. */
  members: string[];
  /** Statements placing each API key on the outgoing request. */
  inject: string[];
  notes: string[];
};

function authSource(required: string[], declared: Json): AuthSource {
  const kinds = new Set<string>();
  const fields: string[] = [];
  const inject: string[] = [];
  const notes: string[] = [];
  for (const name of required) {
    const scheme = declared[name];
    if (!isJson(scheme)) {
      notes.push(
        `security scheme "${name}" is not declared to openapi() or docs(): the client cannot send it`,
      );
    } else if (scheme.type === 'apiKey') {
      if (name === 'type') {
        throw new Error(
          'an apiKey security scheme named "type" collides with the auth option\'s own field — rename the scheme',
        );
      }
      const value = `auth[${literal(name)}]`;
      const target = scheme.in === 'query'
        ? `(endpoint.query ??= {})[${literal(scheme.name)}] = ${value}`
        : scheme.in === 'header'
        ? `headers[${literal(scheme.name)}] = ${value}`
        : `headers.Cookie = [
        headers.Cookie,
        ${literal(`${scheme.name}=`)} + encodeURIComponent(${value}),
      ].filter(Boolean).join('; ')`;
      fields.push(`${key(name)}?: string`);
      inject.push(`if (typeof ${value} === 'string') {
      ${target};
    }`);
    } else if (scheme.type === 'http' && scheme.scheme === 'basic') {
      kinds.add('BASIC');
    } else if (scheme.type === 'http' && scheme.scheme !== 'bearer') {
      notes.push(
        `security scheme "${name}" uses HTTP ${scheme.scheme}: the client cannot send it`,
      );
    } else {
      // http bearer, oauth2 and openIdConnect all end in a bearer token.
      kinds.add('BEARER');
    }
  }
  return {
    members: [
      ...(kinds.has('BEARER')
        ? [`{ type: 'BEARER'; token: string; prefix?: string }`]
        : []),
      ...(kinds.has('BASIC')
        ? [`{ type: 'BASIC'; username: string; password: string }`]
        : []),
      ...(fields.length > 0
        ? [`{ type: 'CUSTOM'; ${fields.join('; ')} }`]
        : []),
    ],
    inject,
    notes,
  };
}

function errorsFile(name: string, constant: string, codes: string[]): string {
  return `/**
 * @fileoverview The error model of the ${name} client. Generated by
 * \`rapid sdk\` — regenerate rather than edit.
 * @module
 */
import { RESTlerError } from '@tundralibs/restler';

/**
 * Error code → message template. \`RAPID_*\` codes are the server's own and
 * carry its message; the rest are raised by this client.
 */
export const ${constant}_ERROR_CODES = {
  UNKNOWN_ERROR:
    'The API answered with an error this client does not know (HTTP \${status}).',
  REQUEST_INVALID: 'The \${what} is invalid; the request was not sent.',
  RESPONSE_INVALID:
    'The reply to \${operation} did not match its declared schema.',
  RATE_LIMITED: 'Still rate limited after the retry (HTTP 429).',
  TIMEOUT: 'No answer within the \${timeoutSeconds}s timeout.',
  NETWORK_ERROR:
    'The request failed before a response (DNS, TLS or connection failure).',
${codes.map((code) => `  ${code}: '\${serverMessage}',`).join('\n')}
} as const;

/** A valid ${name} error code. */
export type ${name}ErrorCode = keyof typeof ${constant}_ERROR_CODES;

/** Metadata carried by a {@link ${name}Error}. */
export type ${name}ErrorMetadata = {
  vendor: string;
  /** The server's code, when this client does not know it. */
  originalCode?: string;
} & Record<string, unknown>;

const TRANSIENT_CODES = new Set<string>([
  'RATE_LIMITED',
  'TIMEOUT',
  'NETWORK_ERROR',
]);
const TRANSIENT_STATUSES = new Set<unknown>([429, 502, 503, 504]);

/**
 * Every failure the ${name} client throws. Branch on \`code\`; the HTTP
 * \`status\`, the server's \`details\` and its \`requestId\` are read with
 * \`getContextValue()\`.
 */
export class ${name}Error<
  M extends ${name}ErrorMetadata = ${name}ErrorMetadata,
> extends RESTlerError<M> {
  /** A key of {@link ${constant}_ERROR_CODES}. */
  public readonly code: ${name}ErrorCode;
  /** \`true\` when retrying later can help: no answer, a 429 or a 502-504. */
  public readonly transient: boolean;

  protected override get _messageTemplate(): string {
    return '[${name}] \${timeStamp}: \${message}';
  }

  constructor(code: ${name}ErrorCode, meta?: Omit<M, 'vendor'>, cause?: Error) {
    const context = { ...meta, vendor: '${name}' } as M;
    if (!(code in ${constant}_ERROR_CODES)) {
      context.originalCode = code;
      code = 'UNKNOWN_ERROR';
    }
    // A placeholder the throw site did not fill would render literally.
    for (const match of ${constant}_ERROR_CODES[code].matchAll(/\\$\\{(\\w+)\\}/g)) {
      const key = String(match[1]);
      if ((context as Record<string, unknown>)[key] === undefined) {
        (context as Record<string, unknown>)[key] = \`<\${key} unavailable>\`;
      }
    }
    super(${constant}_ERROR_CODES[code], context, cause);
    this.code = code;
    this.transient = TRANSIENT_CODES.has(code) ||
      TRANSIENT_STATUSES.has(context.status);
  }
}
`;
}

