/**
 * @fileoverview `rapid modules [dir]` — regenerate the modules barrel.
 * Static-parse each file for a concrete `export class X` (skipping
 * `export abstract class`, which auto-excludes bases), emit sorted
 * re-exports between `// rapid:start` and `// rapid:end`. Lines outside
 * the markers are the author's and survive a regenerate. `--check` fails
 * when the marked region is stale.
 * @module
 */
import { readDir, readTextFile, writeTextFile } from '@tundralibs/compat/file';

const START = '// rapid:start';
const END = '// rapid:end';
const INTRO =
  '// `rapid modules` rewrites the lines between rapid:start and rapid:end.\n' +
  '// Anything outside them is kept.\n';
// What a barrel started with before the markers existed.
const LEGACY_HEADER =
  '// Generated by `rapid modules` — do not edit by hand.\n';
const SKIP = /(^|\/)(mod\.ts|.*\.(test|bench)\.ts|_.*|\..*)$/;

/** Concrete (non-abstract) exported class names in `source`, in order. */
export function exportedClasses(source: string): string[] {
  const names: string[] = [];
  const re = /^export\s+(abstract\s+)?class\s+([A-Za-z_$][\w$]*)/gm;
  for (let m = re.exec(source); m !== null; m = re.exec(source)) {
    if (m[1] === undefined) names.push(m[2]!); // skip `abstract`
  }
  return names;
}

const block = (lines: string[]): string =>
  [START, ...lines, END].join('\n') + '\n';

/**
 * Split `text` around its marked region; `undefined` when it has no marker.
 *
 * @throws {Error} when the markers are unpaired, repeated or out of order.
 */
function splitAtMarkers(
  text: string,
): { before: string; block: string; after: string } | undefined {
  const lines = text.split('\n');
  const at = (marker: string) =>
    lines.flatMap((line, i) => line.trim() === marker ? [i] : []);
  const starts = at(START);
  const ends = at(END);
  if (starts.length === 0 && ends.length === 0) return undefined;
  const [start, end] = [starts[0], ends[0]];
  if (
    starts.length !== 1 || ends.length !== 1 || start === undefined ||
    end === undefined || start > end
  ) {
    throw new Error(`needs exactly one \`${START}\` above one \`${END}\``);
  }
  return {
    before: lines.slice(0, start).map((line) => `${line}\n`).join(''),
    block: lines.slice(start, end + 1).join('\n') + '\n',
    after: lines.slice(end + 1).join('\n'),
  };
}

/**
 * The sorted re-export lines for `dir`.
 *
 * @throws {Error} when two files export a class of the same name — the
 *   barrel would be ambiguous; the message names both files.
 */
async function exportLines(dir: string): Promise<string[]> {
  const lines: string[] = [];
  const files: string[] = [];
  for await (const entry of readDir(dir)) {
    if (entry.isFile && entry.name.endsWith('.ts') && !SKIP.test(entry.name)) {
      files.push(entry.name);
    }
  }
  files.sort((a, b) => a.localeCompare(b));
  const seen = new Map<string, string>();
  for (const file of files) {
    const classes = exportedClasses(await readTextFile(`${dir}/${file}`));
    for (const name of classes.sort((a, b) => a.localeCompare(b))) {
      // Two files exporting one class name would emit two `export { X }`
      // lines — a barrel that fails to compile. Name both offenders.
      const prior = seen.get(name);
      if (prior !== undefined) {
        throw new Error(
          `module class '${name}' is exported by both ${prior} and ${file} — rename one`,
        );
      }
      seen.set(name, file);
      lines.push(`export { ${name} } from './${file}';`);
    }
  }
  return lines;
}

/**
 * Build the text of a new barrel for `dir` (does not write).
 *
 * @throws {Error} when two files export a class of the same name; the
 *   message names both files.
 */
export async function generateBarrel(dir: string): Promise<string> {
  return INTRO + block(await exportLines(dir));
}

/** The `modules` command. Returns the process exit code.
 * `log` receives the success and warning lines; tests pass a no-op. */
export async function modulesCommand(
  dir: string,
  opts: { check?: boolean; force?: boolean } = {},
  log: (line: string) => void = console.log,
): Promise<number> {
  let lines: string[];
  try {
    lines = await exportLines(dir);
  } catch (error) {
    console.error(
      `✗ ${error instanceof Error ? error.message : String(error)}`,
    );
    return 1;
  }
  const fresh = block(lines);
  const out = `${dir}/mod.ts`;
  let existing: string | undefined;
  try {
    existing = await readTextFile(out);
  } catch { /* missing */ }
  let parts: ReturnType<typeof splitAtMarkers>;
  let malformed: string | undefined;
  try {
    parts = existing === undefined ? undefined : splitAtMarkers(existing);
  } catch (error) {
    malformed = (error as Error).message;
  }
  if (opts.check) {
    if (parts?.block !== fresh) {
      console.error(`✗ ${out} is stale — run \`rapid modules ${dir}\``);
      return 1;
    }
    log(`✓ ${out} is up to date`);
    return 0;
  }
  let next = INTRO + fresh;
  if (parts !== undefined) {
    // Only the marked region is ours; the rest of the file is the author's.
    next = parts.before + fresh + parts.after;
  } else if (existing !== undefined) {
    if (malformed === undefined && existing.startsWith(LEGACY_HEADER)) {
      // A barrel from before the markers: replaced whole, once. Say what
      // goes, since the old header promised nothing outside it would survive.
      const dropped = existing.slice(LEGACY_HEADER.length).split('\n')
        .filter((line) => line.trim() !== '' && !lines.includes(line));
      if (dropped.length > 0) {
        log(
          `⚠ ${out} now uses rapid:start / rapid:end markers; dropped ${dropped.length} line(s) the generator did not write:\n` +
            dropped.map((line) => `    ${line}`).join('\n'),
        );
      }
    } else if (opts.force !== true) {
      // A hand-written barrel — or a package's public mod.ts reached via the
      // wrong dir — is refused unless --force says so.
      console.error(
        malformed === undefined
          ? `✗ ${out} exists and has no rapid:start / rapid:end markers — pass --force to overwrite it`
          : `✗ ${out} ${malformed} — fix the markers or pass --force to overwrite it`,
      );
      return 1;
    }
  }
  await writeTextFile(out, next);
  log(`✓ wrote ${out}`);
  return 0;
}
